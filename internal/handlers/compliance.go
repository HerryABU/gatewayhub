package handlers

import (
	"github.com/gin-gonic/gin"
)

// Provision 法律条文
type Provision struct {
	Law     string `json:"law"`
	Article string `json:"article"`
	Title   string `json:"title"`
	Text    string `json:"text"`
	Relevance string `json:"relevance"`
}

// 依据《中华人民共和国网络安全法（2025年修正）》
// 说明：该法 2025 年修正后共 81 条，本项目落地其中与网关日志留存、访问者信息采集最相关的条款。
func complianceProvisions() []Provision {
	return []Provision{
		{
			Law:     "《中华人民共和国网络安全法》（2025年修正）",
			Article: "第二十三条",
			Title:   "网络安全等级保护与网络日志留存",
			Text: "国家实行网络安全等级保护制度。网络运营者应当按照网络安全等级保护制度的要求，履行下列安全保护义务，保障网络免受干扰、破坏或者未经授权的访问，防止网络数据泄露或者被窃取、篡改：（一）制定内部安全管理制度和操作规程，确定网络安全负责人，落实网络安全保护责任；（二）采取防范计算机病毒和网络攻击、网络侵入等危害网络安全行为的技术措施；（三）采取监测、记录网络运行状态、网络安全事件的技术措施，并按照规定留存相关的网络日志不少于六个月；（四）采取数据分类、重要数据备份和加密等措施；（五）法律、行政法规规定的其他义务。",
			Relevance: "本项目对访问日志默认保留 180 天（6 个月），并支持管理员手动清理（仅可清理超出保留期的数据），以满足“网络日志留存不少于六个月”的合规要求。",
		},
		{
			Law:     "《中华人民共和国网络安全法》（2025年修正）",
			Article: "第四十二条",
			Title:   "用户信息保密义务",
			Text: "网络运营者应当对其收集的用户信息严格保密，并建立健全用户信息保护制度。网络运营者处理个人信息，应当遵守本法和《中华人民共和国民法典》《中华人民共和国个人信息保护法》等法律、行政法规的规定。",
			Relevance: "本项目采集的访问者 IP、访问来源地区/城市等信息属于个人信息范畴，仅用于安全审计与流量统计，不对第三方公开。",
		},
		{
			Law:     "《中华人民共和国网络安全法》（2025年修正）",
			Article: "第四十三条",
			Title:   "个人信息收集的合法正当必要原则",
			Text: "网络运营者收集、使用个人信息，应当遵循合法、正当、必要的原则，公开收集、使用规则，明示收集、使用信息的目的、方式和范围，并经被收集者同意。网络运营者不得收集与其提供的服务无关的个人信息，不得违反法律、行政法规的规定和双方的约定收集、使用个人信息，并应当依照法律、行政法规的规定和与用户的约定，处理其保存的个人信息。",
			Relevance: "网关仅在“统一接入与访问统计”这一正当目的范围内，最小化采集访问来源的省级/城市级信息，用于合规审计与可视化统计。",
		},
		{
			Law:     "《中华人民共和国网络安全法》（2025年修正）",
			Article: "第四十四条",
			Title:   "个人信息安全保障",
			Text: "网络运营者不得泄露、篡改、毁损其收集的个人信息；未经被收集者同意，不得向他人提供个人信息。但是，经过处理无法识别特定个人且不能复原的除外。网络运营者应当采取技术措施和其他必要措施，确保其收集的个人信息安全，防止信息泄露、毁损、丢失。在发生或者可能发生个人信息泄露、毁损、丢失的情况时，应当立即采取补救措施，按照规定及时告知用户并向有关主管部门报告。",
			Relevance: "地理位置数据仅以聚合统计形式展示（省级/城市级分布），不展示单个访问者的精确坐标；访问日志访问受管理员权限保护。",
		},
	}
}

// GetCompliance GET /api/compliance
func (h *Handler) GetCompliance(c *gin.Context) {
	h.ok(c, gin.H{
		"law":        "《中华人民共和国网络安全法》（2025年修正）",
		"total_articles": 81,
		"note":       "该法 2025 年修正后共 81 条（第一章总则至第七章附则），于 2026 年 1 月 1 日起施行。本项目已落地与网关日志留存、访问者信息采集最相关的条款。",
		"log_retention_days": h.Cfg.Stats.RetainDays,
		"provisions":  complianceProvisions(),
	})
}
